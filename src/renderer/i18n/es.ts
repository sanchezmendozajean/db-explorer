/** Título legible de un comando (o su id si no tiene texto). */
export function commandTitle(id: string): string {
  const openTab = /^db\.openTab(\d)$/.exec(id);
  if (openTab) return (es.commands['db.openTab'] as (n: number) => string)(Number(openTab[1]));
  const text = es.commands[id];
  return typeof text === 'string' ? text : id;
}
