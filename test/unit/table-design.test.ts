import { describe, expect, it } from 'vitest';
import type { ColumnInfo } from '@shared/metadata';
import {
  buildAlterStatements,
  buildCreateStatements,
  columnFromInfo,
  editableFields,
  newDesignColumn,
  validateDesign,
  type TableDesign,
} from '@shared/table-design';

const info = (over: Partial<ColumnInfo> = {}): ColumnInfo => ({
  name: 'nombre',
  nativeType: 'varchar(50)',
  nullable: true,
  primaryKey: false,
  ...over,
});

const designOf = (...columns: ColumnInfo[]): TableDesign => ({
  name: 'Persona',
  columns: columns.map((c, i) => columnFromInfo(`k${i}`, c)),
});

describe('buildCreateStatements', () => {
  const draft = (engine: 'postgres' | 'mariadb' | 'sqlserver' | 'sqlite'): TableDesign => ({
    name: 'Clientes',
    columns: [
      newDesignColumn(engine, 'a', {
        name: 'id',
        type: engine === 'sqlite' ? 'INTEGER' : 'int',
        nullable: false,
        primaryKey: true,
        autoIncrement: true,
      }),
      newDesignColumn(engine, 'b', {
        name: 'nombre',
        type: engine === 'sqlite' ? 'TEXT' : 'varchar(100)',
        nullable: false,
      }),
    ],
  });

  it('PostgreSQL usa identidad', () => {
    expect(buildCreateStatements('postgres', 'public', draft('postgres'))).toEqual([
      'CREATE TABLE public."Clientes" (\n  id int GENERATED BY DEFAULT AS IDENTITY NOT NULL,\n  nombre varchar(100) NOT NULL,\n  PRIMARY KEY (id)\n)',
    ]);
  });
  it('MariaDB usa AUTO_INCREMENT', () => {
    expect(buildCreateStatements('mariadb', 'bd', draft('mariadb'))[0]).toContain(
      'id int NOT NULL AUTO_INCREMENT',
    );
  });
  it('SQL Server usa IDENTITY', () => {
    expect(buildCreateStatements('sqlserver', 'dbo', draft('sqlserver'))[0]).toContain(
      'id int IDENTITY(1,1) NOT NULL',
    );
  });
  it('SQLite lleva la clave en la columna', () => {
    expect(buildCreateStatements('sqlite', 'main', draft('sqlite'))[0]).toBe(
      'CREATE TABLE Clientes (\n  id INTEGER PRIMARY KEY AUTOINCREMENT,\n  nombre TEXT NOT NULL\n)',
    );
  });
  it('PostgreSQL agrega los comentarios aparte', () => {
    const d = draft('postgres');
    d.columns[1]!.comment = "it's";
    expect(buildCreateStatements('postgres', 'public', d)[1]).toBe(
      `COMMENT ON COLUMN public."Clientes".nombre IS 'it''s'`,
    );
  });
});

describe('buildAlterStatements', () => {
  it('sin cambios no genera nada', () => {
    expect(buildAlterStatements('postgres', 'public', 'Persona', designOf(info()))).toEqual([]);
  });

  it('PostgreSQL: renombrar, tipo, nulo, default y agregar columna', () => {
    const d = designOf(info());
    const c = d.columns[0]!;
    c.name = 'nombre_completo';
    c.type = 'varchar(120)';
    c.nullable = false;
    c.defaultValue = "'x'";
    d.columns.push(newDesignColumn('postgres', 'n', { name: 'edad', type: 'integer' }));
    expect(buildAlterStatements('postgres', 'public', 'Persona', d)).toEqual([
      'ALTER TABLE public."Persona" RENAME COLUMN nombre TO nombre_completo',
      'ALTER TABLE public."Persona" ALTER COLUMN nombre_completo TYPE varchar(120)',
      'ALTER TABLE public."Persona" ALTER COLUMN nombre_completo SET NOT NULL',
      `ALTER TABLE public."Persona" ALTER COLUMN nombre_completo SET DEFAULT 'x'`,
      'ALTER TABLE public."Persona" ADD COLUMN edad integer',
    ]);
  });

  it('elimina columnas primero', () => {
    const d = designOf(info(), info({ name: 'otra' }));
    d.columns[0]!.deleted = true;
    expect(buildAlterStatements('mariadb', 'bd', 'Persona', d)).toEqual([
      'ALTER TABLE bd.Persona DROP COLUMN nombre',
    ]);
  });

  it('MariaDB: MODIFY repite AUTO_INCREMENT, comentario y el default existente', () => {
    const d = designOf(
      info({ name: 'n', nativeType: 'int(11)', nullable: false, autoIncrement: true, defaultValue: '5' }),
    );
    d.columns[0]!.type = 'bigint';
    expect(buildAlterStatements('mariadb', 'bd', 'Persona', d)).toEqual([
      'ALTER TABLE bd.Persona MODIFY COLUMN n bigint NOT NULL DEFAULT 5 AUTO_INCREMENT',
    ]);
  });

  it('MariaDB: un default de texto sin comillas (MySQL 8) se vuelve a entrecomillar', () => {
    const d = designOf(info({ defaultValue: 'activo' }));
    d.columns[0]!.nullable = false;
    expect(buildAlterStatements('mariadb', 'bd', 'Persona', d)[0]).toContain("DEFAULT 'activo'");
  });

  it('SQL Server: sp_rename, ALTER COLUMN y default por restricción', () => {
    const d = designOf(info({ defaultValue: '((1))' }));
    const c = d.columns[0]!;
    c.name = 'otro';
    c.type = 'nvarchar(80)';
    c.defaultValue = '2';
    const sql = buildAlterStatements('sqlserver', 'dbo', 'Persona', d);
    expect(sql[0]).toBe("EXEC sp_rename N'dbo.Persona.nombre', N'otro', N'COLUMN'");
    expect(sql[1]).toBe('ALTER TABLE dbo.Persona ALTER COLUMN otro nvarchar(80) NULL');
    expect(sql[2]).toContain('DROP CONSTRAINT');
    expect(sql[3]).toBe('ALTER TABLE dbo.Persona ADD DEFAULT 2 FOR otro');
  });

  it('SQLite solo renombra, agrega y elimina', () => {
    const d = designOf(info());
    d.columns[0]!.name = 'otro';
    d.columns[0]!.type = 'TEXT';
    d.columns.push(newDesignColumn('sqlite', 'n', { name: 'edad', type: 'INTEGER' }));
    expect(buildAlterStatements('sqlite', 'main', 'Persona', d)).toEqual([
      'ALTER TABLE Persona RENAME COLUMN nombre TO otro',
      'ALTER TABLE Persona ADD edad INTEGER',
    ]);
  });
});

describe('editableFields y validateDesign', () => {
  it('SQLite no deja modificar el tipo de una columna existente, pero sí de una nueva', () => {
    const existing = columnFromInfo('a', info());
    expect(editableFields('sqlite', false, existing).type).toBe(false);
    expect(editableFields('sqlite', false, newDesignColumn('sqlite', 'b')).type).toBe(true);
    expect(editableFields('postgres', false, existing).type).toBe(true);
  });

  it('la clave y el autoincremento solo se definen al crear la tabla', () => {
    const c = newDesignColumn('postgres', 'a');
    expect(editableFields('postgres', false, c).primaryKey).toBe(false);
    expect(editableFields('postgres', true, c).primaryKey).toBe(true);
  });

  it('valida nombre, duplicados, tipo y autoincremento', () => {
    const d: TableDesign = {
      name: ' ',
      columns: [
        newDesignColumn('postgres', 'a', { name: 'x', type: '' }),
        newDesignColumn('postgres', 'b', { name: 'X', autoIncrement: true, type: 'text' }),
      ],
    };
    expect(validateDesign('postgres', d, true).map((i) => i.code)).toEqual([
      'nameRequired',
      'typeRequired',
      'columnDuplicate',
      'autoIncrementType',
      'autoIncrementKey',
    ]);
    expect(validateDesign('postgres', { name: '', columns: [] }, false)).toEqual([{ code: 'noColumns' }]);
  });
});
